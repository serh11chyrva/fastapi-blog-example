"""Small generated PNG fixtures stored in the configured private image buckets."""

import asyncio
import struct
import zlib
from urllib.request import Request, urlopen
from uuid import NAMESPACE_URL, uuid5

from botocore.exceptions import ClientError

from backend.core.config import get_settings
from backend.core.resources import AppResources
from backend.storage.models import ImagePurpose


def png_chunk(kind: bytes, data: bytes) -> bytes:
    """Encode a length-prefixed PNG chunk with its checksum.

    :param kind: Four-byte PNG chunk identifier.
    :param data: Raw chunk payload.
    :return: The complete encoded chunk.
    """
    return struct.pack("!I", len(data)) + kind + data + struct.pack("!I", zlib.crc32(kind + data))


def landscape_png(palette: int, width: int, height: int) -> bytes:
    """Draw a deterministic geometric landscape without external images or imaging dependencies.

    :param palette: Color variation used to distinguish profiles and publication images.
    :param width: Canvas width in pixels.
    :param height: Canvas height in pixels.
    :return: A complete RGB PNG image.
    """
    colors = [(40, 96, 112), (127, 75, 64), (79, 89, 131), (91, 115, 74), (158, 112, 52)]
    red, green, blue = colors[palette % len(colors)]
    rows = bytearray()

    for y in range(height):
        rows.append(0)

        for x in range(width):
            shade = y * 50 // height
            color = (min(red + 85 - shade, 255), min(green + 75 - shade, 255), min(blue + 65 - shade, 255))

            if (x - width * 3 // 4) ** 2 + (y - height // 3) ** 2 < (height // 9) ** 2:
                color = (248, 220, 157)

            ridge = height * 3 // 5 - abs(x - width // 3) // 3
            if y > ridge:
                color = (red, green, blue)
            if y > height * 4 // 5 + (x % (width // 3)) // 5:
                color = (red // 2, green // 2, blue // 2)

            rows.extend(color)

    header = struct.pack("!2I5B", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", header)
        + png_chunk(b"IDAT", zlib.compress(rows)) + png_chunk(b"IEND", b"")
    )


def put_png(resources: AppResources, bucket: str, key: str, data: bytes) -> None:
    """Upload generated bytes through an internally signed S3 PUT without overwriting an existing object.

    :param resources: Application S3 client using the internal Docker endpoint.
    :param bucket: Configured private image bucket.
    :param key: Stable object key reserved for this demo fixture.
    :param data: Generated PNG bytes.
    :return: None.
    """
    try:
        resources.s3.head_object(Bucket=bucket, Key=key)
        return
    except ClientError as exc:
        if exc.response["Error"]["Code"] not in {"404", "NoSuchKey", "NotFound"}:
            raise

    url = resources.s3.generate_presigned_url(
        "put_object", Params={"Bucket": bucket, "Key": key, "ContentType": "image/png"},
        ExpiresIn=600, HttpMethod="PUT",
    )
    request = Request(url, data=data, headers={"Content-Type": "image/png"}, method="PUT")

    with urlopen(request, timeout=15) as response:
        response.read()


async def ensure_image(
    resources: AppResources, purpose: ImagePurpose, name: str, palette: int = 0,
) -> str:
    """Ensure one stable demo PNG exists in the correct private bucket.

    :param resources: Application S3 client container.
    :param purpose: Image collection determining its bucket and public path.
    :param name: Stable fixture name used to derive a collision-resistant object key.
    :param palette: Color variation for the generated landscape.
    :return: The stored image key, ready to attach to its owning fixture.
    """
    settings = get_settings()
    bucket = settings.avatar_bucket if purpose in {"avatars", "profile-banners"} else settings.publication_bucket
    key = f"{purpose}/{uuid5(NAMESPACE_URL, f'commonplace-demo-v2:{purpose}:{name}').hex}.png"
    width, height = {"avatars": (160, 160), "profile-banners": (1200, 360)}.get(purpose, (720, 400))
    data = await asyncio.to_thread(landscape_png, palette, width, height)
    await asyncio.to_thread(put_png, resources, bucket, key, data)

    return key
